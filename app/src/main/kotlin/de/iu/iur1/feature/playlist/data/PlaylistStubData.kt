    private val today = randomEntries()
    private val buffer: ConcurrentHashMap<LocalDate, PlaylistData> = ConcurrentHashMap()

    fun of(date: LocalDate): PlaylistData {
        val now = LocalDate.now()
        if (date.isEqual(now)) {
            val now = LocalTime.now()
            val entriesToday = mutableListOf<PlaylistEntry>()
            entriesToday.addAll(today)
            entriesToday.removeIf {
                val time = LocalTime.parse(it.time)
                time.isBefore(startTime) || time.isAfter(now)
            }

            return PlaylistData(rating = 5, entries = entriesToday)
        }

        return buffer.computeIfAbsent(date) {
            PlaylistData(rating = Random.nextInt(1, 5), entries = randomEntries())
        }
    }

    private fun randomEntries(): List<PlaylistEntry> {
        val retList = mutableListOf<PlaylistEntry>()
        var currentTime = startTime
        for (title in titles.shuffled()) {
            currentTime = currentTime.plusMinutes(Random.nextLong(2, 6))
            if (currentTime.isBefore(startTime)) return retList

            retList.add(PlaylistEntry(title, currentTime.toString()))
            if (Random.nextInt(10) == 9) currentTime = currentTime.plusMinutes(30)
        }
        return retList
    }
